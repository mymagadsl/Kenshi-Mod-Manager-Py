def to_traditional_chinese(text: str) -> str:
    """將簡體中文字串轉換為繁體中文。"""
    if not text:
        return ""
    res = text.translate(_S2T_MAP)
    # 常見詞彙修正
    res = res.replace("幹預", "干預").replace("骨幹", "骨幹").replace("相干", "相干")
    res = res.replace("合並", "合併").replace("假肢", "義肢").replace("模组", "模組")
    return res


def has_chinese(text: str) -> bool:
    """判斷字串是否含有中文字元，且不含日文平假名／片假名。"""
    if not text:
        return False
    if _JP_KANA_RE.search(text):
        return False
    return bool(_CJK_RE.search(text))


def extract_zh_from_title_or_desc(mod: Mod) -> str:
    """從 mod.title 或 mod.description 首行提取乾淨的繁體中文名稱。"""
    # 1. 優先檢查 Steam .info 的 <title>
    if mod.title and has_chinese(mod.title):
        t = _BRACKET_RE_KENSHI.sub("", mod.title).strip()
        # 若標題以 '/' 或 '|' 分隔中英文（如 'Dynamic Refugees / 动态难民事件'），取含中文的那一側
        parts = [p.strip() for p in re.split(r"\s*[/|｜]\s*", t) if p.strip()]
        zh_parts = [p for p in parts if has_chinese(p)]
        picked = zh_parts[0] if zh_parts else t
        # 移除多餘的純英文尾綴（若前面已有完整中文）
        m_paren = re.search(r"[\(（]([^\)）]*[\u4e00-\u9fff][^\)）]*)[\)）]", picked)
        if m_paren and not has_chinese(picked[:m_paren.start()]):
            picked = m_paren.group(1).strip()
        else:
            picked = re.sub(r"\s+[A-Za-z0-9_:\-\s\(\)\.]{6,}$", "", picked).strip()
        picked = to_traditional_chinese(picked)
        if picked:
            return picked

    # 2. 檢查 description 前 3 行是否有明確中文標題（如【绝境系统 ...】或單行中文名稱）
    if mod.description:
        cleaned_desc = _BBCODE_RE.sub("", mod.description)
        for raw_line in cleaned_desc.splitlines()[:4]:
            line = raw_line.strip().lstrip("#*•- ").strip()
            if not line or not has_chinese(line):
                continue
            # 若是【標題】格式
            m_br = re.match(r"^[【\[]([^】\]]+)[】\]]", line)
            if m_br and has_chinese(m_br.group(1)):
                inner = re.sub(r"\([^)]*[A-Za-z]{3,}[^)]*\)", "", m_br.group(1)).strip(" -—|")
                return to_traditional_chinese(inner)
            # 若整行短小且像標題（長度 <= 24 且不含句號或長敘述）
            if len(line) <= 20 and not any(p in line for p in ("。", "，", "http", "：", ":")):
                parts = [p.strip() for p in re.split(r"\s*[/|｜]\s*", line) if has_chinese(p)]
                if parts:
                    return to_traditional_chinese(parts[0])
    return ""


def _load_json_dict(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
        if isinstance(data, dict):
            return {str(k): str(v) for k, v in data.items() if v}
    except (OSError, ValueError):
        pass
    return {}


def load_base_zh_dict(path: Path = constants.BASE_NAMES_ZH_FILE) -> dict[str, str]:
    return _load_json_dict(path)


def load_custom_zh_dict(path: Path = constants.MOD_NAMES_ZH_FILE) -> dict[str, str]:
    return _load_json_dict(path)


def save_custom_zh_name(
    mod_key: str,
    zh_name: str,
    path: Path = constants.MOD_NAMES_ZH_FILE,
) -> None:
    """儲存或移除（當 zh_name 為空字串時）使用者自訂／快取的模組繁中譯名。"""
    data = load_custom_zh_dict(path)
    key = mod_key.strip()
    if key.lower().endswith(".mod"):
        key = key[:-4]
    zh = zh_name.strip()
    if zh:
        data[key] = zh
    else:
        data.pop(key, None)
    try:
        if path.exists():
            try:
                os.chmod(path, stat.S_IWRITE)
            except OSError:
                pass
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    except OSError as exc:
        logging_util.write(constants.ERROR_FILE, f"無法寫入中文名稱設定檔：{path}")
        logging_util.write_exception(constants.ERROR_FILE, exc)


